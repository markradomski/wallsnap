/**
 * Builds the static data for the public demo from the DEV townhouse, read-only:
 *   - public-demo/townhouse.ts   the first floor's walls, openings, rooms, furniture and stairs (plus the ground-floor stair
 *                                that cuts the first-floor slab), with only the fields WallSnap parses and neutral ids
 *   - public-demo/townhouse.glb  the FloorGen GLB export reduced to the first floor and the ground-floor slab, without the
 *                                artwork stand-ins, the second floor, or the export timestamp; the binary is rebuilt so
 *                                removed geometry is not left in the file
 *
 *   npx tsx --env-file=.env public-demo/build-data.ts <path to the FloorGen GLB export>
 *
 * Only read tools are called, through the same write guard as the app.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createGateway } from '../server/index'

const DIR = import.meta.dirname
const FIRST = 'First Floor — Living / Dining / Kitchen'
const GROUND = 'Ground Floor'
type Row = Record<string, unknown>
const rec = (v: unknown) => v as Row

// ---------- plan data ----------
const { gw, project } = createGateway()
const call = async (tool: string, args: Row) => rec((await gw.call(tool, { project, ...args })).data)
const floors = (call('list_floors', {}) as Promise<Row>).then((d) => d.floors as Row[])
const all = await floors
const ground = all.find((f) => f.kind === 'ground')!
const first = all.find((f) => f.name === FIRST)!
const rows = (await call('list_entities', { floor: first.id, detail: 'full', limit: 1000, type: ['room', 'wall', 'opening', 'item', 'stair'] })).rows as Row[]
const below = (await call('list_entities', { floor: ground.id, detail: 'full', limit: 1000, type: ['stair'] })).rows as Row[]

const ids = new Map<string, string>()
const nid = (old: unknown, prefix: string) => {
  const k = String(old)
  if (!ids.has(k)) ids.set(k, `${prefix}${[...ids.values()].filter((v) => v.startsWith(prefix)).length + 1}`)
  return ids.get(k)!
}
const pt = (p: unknown) => ({ x: Number(rec(p).x), y: Number(rec(p).y) })
const of = (t: string) => rows.filter((r) => r.type === t)

const walls = of('wall').map((r) => ({ id: nid(r.id, 'wall_'), type: 'wall', a: pt(r.a), b: pt(r.b), thickness_cm: r.thickness_cm, entity: { height: rec(r.entity).height } }))
const openings = of('opening').map((r) => ({
  id: nid(r.id, 'opening_'), type: 'opening', kind: r.kind, wall_id: nid(r.wall_id, 'wall_'), offset_cm: r.offset_cm, width_cm: r.width_cm,
  rooms: Array.isArray(r.rooms) && r.rooms.includes('exterior') ? ['exterior'] : [],
  entity: { sill: rec(r.entity).sill, height: rec(r.entity).height },
}))
const rooms = of('room').map((r) => {
  const wallIds = (r.wall_ids as unknown[]).map((w) => nid(w, 'wall_'))
  return { id: nid(r.id, 'room_'), type: 'room', key: wallIds.join('|'), name: r.name, wall_ids: wallIds, centroid: pt(r.centroid) }
})
// Furniture only: WallSnap's own artworks are left out, so the demo walls start empty.
const furniture = of('item').filter((r) => r.tag !== 'wallsnap').map((r) => {
  const e = rec(r.entity)
  return { id: nid(r.id, 'item_'), type: 'item', x: r.x, y: r.y, rotation: r.rotation, entity: { width: e.width, depth: e.depth, height: e.height, elevation: e.elevation } }
})
const stair = (r: Row) => {
  const e = rec(r.entity)
  const keep = ['x', 'y', 'rotation', 'width', 'steps', 'treadDepth', 'nosing', 'cutOpening', 'wellGap'] as const
  return { id: nid(r.id, 'stair_'), type: 'stair', entity: Object.fromEntries(keep.filter((k) => e[k] !== undefined).map((k) => [k, e[k]])) }
}

const FLOORS = [
  { id: 'floor_ground', name: GROUND, kind: 'ground', height: ground.height },
  { id: 'floor_first', name: FIRST, kind: first.kind, height: first.height },
]
const ENTITIES = {
  floor_ground: below.map(stair),
  floor_first: [...walls, ...rooms, ...openings, ...furniture, ...of('stair').map(stair)],
}
writeFileSync(join(DIR, 'townhouse.ts'), `// Generated by build-data.ts from the WallSnap DEV townhouse (first floor only, neutral ids). Do not edit.
// Same shape as server/fixture.ts, which the demo build replaces with this file.
type Row = Record<string, unknown>
export const FLOORS = ${JSON.stringify(FLOORS, null, 2)}
export const ENTITIES: Record<string, Row[]> = ${JSON.stringify(ENTITIES, null, 2)}
`)
console.log(`plan: ${walls.length} walls, ${openings.length} openings, ${rooms.length} rooms, ${furniture.length} furniture items, ${ENTITIES.floor_first.length - walls.length - rooms.length - openings.length - furniture.length} stairs, ${below.length} stair below`)

// ---------- GLB ----------
const src = readFileSync(process.argv[2])
const jsonLen = src.readUInt32LE(12)
const g = JSON.parse(src.subarray(20, 20 + jsonLen).toString('utf8'))
const bin = src.subarray(20 + jsonLen + 8)
const STAND_IN = '#4b5a70' // FloorGen's colour for the generic picture items WallSnap places

const roots: number[] = g.scenes[g.scene ?? 0].nodes
const groundRoot = roots.find((r) => g.nodes[r].name.startsWith('Ground Floor'))!
const firstRoot = roots.find((r) => g.nodes[r].name === FIRST)!
g.nodes[groundRoot].name = GROUND
// The ground floor keeps only its slab, so heights still start at Y = 0 and the first floor sits where the plan says.
g.nodes[groundRoot].children = (g.nodes[groundRoot].children ?? []).filter((c: number) => / floors$/.test(g.nodes[c].name))
for (const c of g.nodes[groundRoot].children) g.nodes[c].name = `${GROUND} floors`
g.scenes[g.scene ?? 0].nodes = [groundRoot, firstRoot]
for (const c of g.nodes[firstRoot].children ?? []) {
  const n = g.nodes[c]
  if (n.mesh === undefined) continue
  g.meshes[n.mesh].primitives = g.meshes[n.mesh].primitives.filter((p: { material?: number }) => !String(g.materials[p.material ?? -1]?.name ?? '').startsWith(STAND_IN))
}

// Rebuild: keep only reachable nodes, meshes, materials and accessors, each accessor copied into its own buffer view.
const nodes: Row[] = []
const meshes: Row[] = []
const materials: Row[] = []
const accessors: Row[] = []
const views: Row[] = []
const chunks: Buffer[] = []
let size = 0
const matMap = new Map<number, number>()
const copyAccessor = (i: number) => {
  const a = { ...g.accessors[i] }
  const v = g.bufferViews[a.bufferView]
  const comps: Record<string, number> = { SCALAR: 1, VEC2: 2, VEC3: 3, VEC4: 4 }
  const bytes: Record<number, number> = { 5120: 1, 5121: 1, 5122: 2, 5123: 2, 5125: 4, 5126: 4 }
  const stride = v.byteStride ?? comps[a.type] * bytes[a.componentType]
  const len = stride * (a.count - 1) + comps[a.type] * bytes[a.componentType]
  const start = (v.byteOffset ?? 0) + (a.byteOffset ?? 0)
  const pad = (4 - (size % 4)) % 4
  if (pad) { chunks.push(Buffer.alloc(pad)); size += pad }
  chunks.push(Buffer.from(bin.subarray(start, start + len)))
  views.push({ buffer: 0, byteOffset: size, byteLength: len, ...(v.byteStride ? { byteStride: v.byteStride } : {}), ...(v.target ? { target: v.target } : {}) })
  size += len
  a.bufferView = views.length - 1
  delete a.byteOffset
  accessors.push(a)
  return accessors.length - 1
}
const copyNode = (i: number): number => {
  const n = { ...g.nodes[i] }
  if (n.mesh !== undefined) {
    const m = g.meshes[n.mesh]
    meshes.push({
      ...m,
      primitives: m.primitives.map((p: Row & { attributes: Record<string, number>; indices?: number; material?: number }) => {
        const out: Row = { ...p, attributes: Object.fromEntries(Object.entries(p.attributes).map(([k, v]) => [k, copyAccessor(v)])) }
        if (p.indices !== undefined) out.indices = copyAccessor(p.indices)
        if (p.material !== undefined) {
          if (!matMap.has(p.material)) { materials.push(g.materials[p.material]); matMap.set(p.material, materials.length - 1) }
          out.material = matMap.get(p.material)
        }
        return out
      }),
    })
    n.mesh = meshes.length - 1
  }
  const kids = (g.nodes[i].children ?? []).map(copyNode)
  nodes.push(n)
  const at = nodes.length - 1
  if (kids.length) n.children = kids
  else delete n.children
  return at
}
const sceneRoots = [groundRoot, firstRoot].map(copyNode)
const extras = g.asset.extras?.provenance ? { provenance: { ...g.asset.extras.provenance } } : undefined
if (extras) delete extras.provenance.created
const out = {
  asset: { version: '2.0', generator: g.asset.generator, ...(extras ? { extras } : {}) },
  scene: 0, scenes: [{ nodes: sceneRoots }], nodes, meshes, materials, accessors, bufferViews: views,
  buffers: [{ byteLength: size }],
}
const binOut = Buffer.concat([...chunks, Buffer.alloc((4 - (size % 4)) % 4)])
let json = Buffer.from(JSON.stringify(out))
json = Buffer.concat([json, Buffer.alloc((4 - (json.length % 4)) % 4, 0x20)])
const head = Buffer.alloc(12)
head.writeUInt32LE(0x46546c67, 0); head.writeUInt32LE(2, 4); head.writeUInt32LE(12 + 8 + json.length + 8 + binOut.length, 8)
const ch = (type: number, data: Buffer) => { const h = Buffer.alloc(8); h.writeUInt32LE(data.length, 0); h.writeUInt32LE(type, 4); return Buffer.concat([h, data]) }
writeFileSync(join(DIR, 'townhouse.glb'), Buffer.concat([head, ch(0x4e4f534a, json), ch(0x004e4942, binOut)]))
console.log(`glb: ${nodes.length} nodes, ${meshes.length} meshes, ${materials.length} materials, ${size} bytes of geometry`)
